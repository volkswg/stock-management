-- Phase 2: private operational state, separate from the frozen import archive.
CREATE SCHEMA stock_operational;
REVOKE ALL ON SCHEMA stock_operational FROM PUBLIC, anon, authenticated;
DO $$ BEGIN IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname='stock_runtime') THEN CREATE ROLE stock_runtime NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOBYPASSRLS; ELSIF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='stock_runtime' AND (rolcanlogin OR rolsuper OR rolcreatedb OR rolcreaterole OR rolinherit OR rolbypassrls)) THEN RAISE EXCEPTION 'Unexpected stock_runtime privileges'; END IF; END $$;
GRANT USAGE ON SCHEMA stock_operational TO stock_runtime;
CREATE TABLE stock_operational.commands (actor text NOT NULL, kind text NOT NULL, key text NOT NULL, intent text NOT NULL, state text NOT NULL CHECK (state IN ('pending','complete')), response jsonb, created_at timestamptz NOT NULL DEFAULT now(), completed_at timestamptz, PRIMARY KEY(actor,kind,key));
CREATE TABLE stock_operational.audit (sequence bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY, table_name text NOT NULL, record_id text NOT NULL, old_record jsonb, new_record jsonb, command_key text NOT NULL, changed_at timestamptz NOT NULL DEFAULT now());
CREATE FUNCTION stock_operational.audit_change() RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER SET search_path = '' AS $$ BEGIN INSERT INTO stock_operational.audit(table_name,record_id,old_record,new_record,command_key) VALUES (TG_TABLE_NAME, coalesce(to_jsonb(NEW)->>'id',to_jsonb(NEW)->>'migration_id'), CASE WHEN TG_OP = 'UPDATE' THEN to_jsonb(OLD) END,to_jsonb(NEW),coalesce(current_setting('stock.command_key',true),'promotion')); RETURN NEW; END $$;
REVOKE ALL ON FUNCTION stock_operational.audit_change() FROM PUBLIC;
